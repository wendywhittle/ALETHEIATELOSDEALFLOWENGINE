"""AletheiaTelos DealFlow Engine — canonical deal record persistence.

One SQLite table (`deals`). The record is the canonical source of truth:

  identity          deal_id, name, asset_type, location
  original_inputs   the 11 validated financial inputs, exactly as submitted
  underwriting      deterministic results with provenance (from underwriting.py)
  workflow          status, created_at, updated_at, artifact_reference
  contact           name / email / phone as submitted

Rules:
  - Deal IDs are generated by the application as AT-YYYY-NNNNNN from the
    database row id. They never depend on property data.
  - Original inputs are never overwritten by calculations; underwriting
    results live in their own JSON column.
  - Missing information stays explicit (None in inputs, "unavailable" in
    underwriting).
  - Status transitions are human-controlled: NEW -> REVIEWING -> PURSUE/HOLD/PASS,
    with reopening back to REVIEWING allowed. Terminal states cannot jump
    arbitrarily.

The submission path used by the web app AND the import CLI is submit_deal():
  raw intake dict -> validation -> record -> underwriting -> stored record.
"""

import datetime
import json
import os
import sqlite3

import underwriting
import validation

REPO_DIR = os.path.dirname(os.path.abspath(__file__))
DEFAULT_DB = os.path.join(REPO_DIR, "dealflow.db")

STATUSES = ("NEW", "REVIEWING", "PURSUE", "HOLD", "PASS")

# ---------- due diligence ----------

DD_STATUSES = ("not_started", "requested", "received", "in_review",
               "cleared", "waived", "issue")

# (category, item_key, label) — the standard CRE checklist seeded for every deal.
DD_CHECKLIST = [
    ("Legal / Title", "purchase_agreement", "Purchase agreement"),
    ("Legal / Title", "title_commitment", "Title commitment"),
    ("Legal / Title", "title_exceptions", "Title exceptions reviewed"),
    ("Legal / Title", "survey", "Survey"),
    ("Legal / Title", "zoning_verification", "Zoning verification"),
    ("Financial", "rent_roll", "Rent roll"),
    ("Financial", "leases", "Leases"),
    ("Financial", "operating_statements", "12-month operating statements"),
    ("Financial", "tax_returns", "Tax returns"),
    ("Financial", "estoppels", "Estoppel certificates"),
    ("Physical / Environmental", "inspection", "Property inspection"),
    ("Physical / Environmental", "phase_i", "Environmental Phase I"),
    ("Physical / Environmental", "major_systems", "Major systems (roof / HVAC)"),
    ("Insurance / Compliance", "insurance_quotes", "Insurance quotes"),
    ("Insurance / Compliance", "flood_zone", "Flood zone determination"),
    ("Insurance / Compliance", "permits_co", "Permits / certificate of occupancy"),
    ("Association", "hoa_docs", "HOA / condo docs (waive if not applicable)"),
    ("Financing", "loan_term_sheet", "Loan term sheet"),
    ("Financing", "appraisal", "Appraisal"),
]

DD_CATEGORIES = []
for _cat, _key, _label in DD_CHECKLIST:
    if _cat not in DD_CATEGORIES:
        DD_CATEGORIES.append(_cat)
del _cat, _key, _label

DD_ITEMS_SCHEMA = """
CREATE TABLE IF NOT EXISTS dd_items (
    id        INTEGER PRIMARY KEY AUTOINCREMENT,
    deal_id   TEXT NOT NULL,
    category  TEXT NOT NULL,
    item_key  TEXT NOT NULL,
    label     TEXT NOT NULL,
    status    TEXT NOT NULL DEFAULT 'not_started',
    notes     TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    UNIQUE (deal_id, item_key)
)
"""

DD_DOCUMENTS_SCHEMA = """
CREATE TABLE IF NOT EXISTS dd_documents (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    deal_id     TEXT NOT NULL,
    item_key    TEXT NOT NULL,
    filename    TEXT NOT NULL,
    stored_path TEXT NOT NULL,
    note        TEXT NOT NULL DEFAULT '',
    uploaded_at TEXT NOT NULL
)
"""

TRANSITIONS = {
    "NEW": {"REVIEWING"},
    "REVIEWING": {"NEW", "PURSUE", "HOLD", "PASS"},
    "PURSUE": {"REVIEWING"},
    "HOLD": {"REVIEWING"},
    "PASS": {"REVIEWING"},
}

SCHEMA = """
CREATE TABLE IF NOT EXISTS deals (
    id               INTEGER PRIMARY KEY AUTOINCREMENT,
    deal_id          TEXT UNIQUE,
    name             TEXT NOT NULL,
    asset_type       TEXT NOT NULL,
    location         TEXT NOT NULL,
    source           TEXT NOT NULL DEFAULT '',
    inputs_json      TEXT NOT NULL,
    underwriting_json TEXT NOT NULL,
    contact_json     TEXT NOT NULL,
    status           TEXT NOT NULL DEFAULT 'NEW',
    artifact_path    TEXT,
    created_at       TEXT NOT NULL,
    updated_at       TEXT NOT NULL
)
"""


def _ensure_source_column(conn):
    """Add the `source` column to databases created before it existed."""
    cols = [r[1] for r in conn.execute("PRAGMA table_info(deals)").fetchall()]
    if "source" not in cols:
        conn.execute("ALTER TABLE deals ADD COLUMN source TEXT NOT NULL DEFAULT ''")
        conn.commit()


def _db_path(path=None):
    return path or os.environ.get("DEALFLOW_DB", DEFAULT_DB)


def _connect(path=None):
    conn = sqlite3.connect(_db_path(path))
    conn.row_factory = sqlite3.Row
    conn.execute(SCHEMA)
    conn.execute(DD_ITEMS_SCHEMA)
    conn.execute(DD_DOCUMENTS_SCHEMA)
    conn.commit()
    _ensure_source_column(conn)
    return conn


def _now_iso():
    return datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds")


def _row_to_deal(row):
    keys = row.keys()
    return {
        "deal_id": row["deal_id"],
        "name": row["name"],
        "asset_type": row["asset_type"],
        "location": row["location"],
        "source": row["source"] if "source" in keys else "",
        "inputs": json.loads(row["inputs_json"]),
        "underwriting": json.loads(row["underwriting_json"]),
        "contact": json.loads(row["contact_json"]),
        "status": row["status"],
        "artifact_path": row["artifact_path"],
        "created_at": row["created_at"],
        "updated_at": row["updated_at"],
    }


def submit_deal(raw, path=None):
    """Validate, persist, and underwrite a deal. Returns the new Deal ID.

    Raises ValueError with a readable message when validation fails.
    This is the single real submission path for the web app and the CLI.
    """
    cleaned, errors = validation.validate(raw)
    if errors:
        raise ValueError("; ".join(e["message"] for e in errors))

    inputs = {f: cleaned.get(f) for f in validation.INPUT_FIELDS}
    contact = {f: cleaned.get(f, "") for f in validation.CONTACT_FIELDS}
    extras = {f: cleaned.get(f, "") for f in validation.EXTRA_FIELDS}

    now = _now_iso()
    conn = _connect(path)
    try:
        cur = conn.execute(
            """INSERT INTO deals
               (name, asset_type, location, source, inputs_json, underwriting_json,
                contact_json, status, created_at, updated_at)
               VALUES (?, ?, ?, ?, ?, ?, ?, 'NEW', ?, ?)""",
            (cleaned["name"], cleaned["asset_type"], cleaned["location"],
             cleaned.get("source", ""),
             json.dumps(inputs), json.dumps({}),
             json.dumps({**contact, **extras}), now, now),
        )
        row_id = cur.lastrowid
        deal_id = "AT-%s-%06d" % (datetime.datetime.now().year, row_id)

        result = underwriting.calculate(inputs)

        conn.execute(
            "UPDATE deals SET deal_id = ?, underwriting_json = ?, updated_at = ? "
            "WHERE id = ?",
            (deal_id, json.dumps(result), _now_iso(), row_id),
        )
        seed_dd_checklist(deal_id, conn)
        conn.commit()
    finally:
        conn.close()
    return deal_id


def get_deal(deal_id, path=None):
    """Return the canonical deal record dict, or None if unknown."""
    conn = _connect(path)
    try:
        row = conn.execute(
            "SELECT * FROM deals WHERE deal_id = ?", (deal_id,)).fetchone()
    finally:
        conn.close()
    return _row_to_deal(row) if row else None


def list_deals(status=None, path=None):
    """Newest-first list of deal records, optionally filtered by status."""
    conn = _connect(path)
    try:
        if status:
            rows = conn.execute(
                "SELECT * FROM deals WHERE status = ? ORDER BY id DESC",
                (status,)).fetchall()
        else:
            rows = conn.execute("SELECT * FROM deals ORDER BY id DESC").fetchall()
    finally:
        conn.close()
    return [_row_to_deal(r) for r in rows]


def set_status(deal_id, new_status, path=None):
    """Human-controlled status change. Enforces the documented transitions."""
    if new_status not in STATUSES:
        raise ValueError("Unknown status: %r" % (new_status,))
    conn = _connect(path)
    try:
        row = conn.execute(
            "SELECT status FROM deals WHERE deal_id = ?", (deal_id,)).fetchone()
        if not row:
            raise ValueError("Unknown deal: %r" % (deal_id,))
        current = row["status"]
        if new_status != current and new_status not in TRANSITIONS[current]:
            raise ValueError(
                "Status change %s -> %s is not allowed." % (current, new_status))
        conn.execute(
            "UPDATE deals SET status = ?, updated_at = ? WHERE deal_id = ?",
            (new_status, _now_iso(), deal_id))
        conn.commit()
    finally:
        conn.close()
    return new_status


def set_artifact(deal_id, artifact_path, path=None):
    """Record the generated Excel artifact reference on the deal."""
    conn = _connect(path)
    try:
        conn.execute(
            "UPDATE deals SET artifact_path = ?, updated_at = ? WHERE deal_id = ?",
            (artifact_path, _now_iso(), deal_id))
        conn.commit()
    finally:
        conn.close()


