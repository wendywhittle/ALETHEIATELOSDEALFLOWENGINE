def dd_progress(deal_id, path=None):
    """Return (cleared_count, total_count) for a deal's DD checklist."""
    conn = _connect(path)
    try:
        row = conn.execute(
            "SELECT COUNT(*) AS total, "
            "SUM(CASE WHEN status = 'cleared' THEN 1 ELSE 0 END) AS cleared "
            "FROM dd_items WHERE deal_id = ?",
            (deal_id,)).fetchone()
    finally:
        conn.close()
    return (row["cleared"] or 0, row["total"] or 0)


def dd_progress_all(path=None):
    """Return {deal_id: (cleared, total)} for every deal with a checklist."""
    conn = _connect(path)
    try:
        rows = conn.execute(
            "SELECT deal_id, COUNT(*) AS total, "
            "SUM(CASE WHEN status = 'cleared' THEN 1 ELSE 0 END) AS cleared "
            "FROM dd_items GROUP BY deal_id").fetchall()
    finally:
        conn.close()
    return {r["deal_id"]: (r["cleared"] or 0, r["total"] or 0) for r in rows}
